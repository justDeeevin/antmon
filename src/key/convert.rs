use x11::keysym::*;

macro_rules! key_conv {
    ($(#[$attr:meta])* $name:ident($platform:ident) {$($p:pat => $key:ident),* $(,)?}) => {
        $(#[$attr])*
        #[doc = concat!("Convert a native ", stringify!($platform), " keycode to its semantic representation.")]
        pub fn $name(code: u32) -> $crate::key::Key {
            use $crate::key::Key;
            match Key::Super {
                $(Key::$key => {})*
                Key::Unknown {..} => {}
            }
            match code {
                $($p => Key::$key,)*
                _ => Key::Unknown {
                    platform: $crate::Platform::$platform,
                    code,
                }
            }
        }
    }
}

